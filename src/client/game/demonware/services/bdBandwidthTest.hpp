#pragma once

namespace demonware
{
	class bdBandwidthTest final : public service
	{
	public:
		bdBandwidthTest() : service(18, "bdBandwidthTest")
		{
		}

		void exec_task(service_server* server, const std::string& data) override
		{
			dw_log(utils::string::va("[bdBandwidthTest 18] (%zu bytes): ", data.size()) + dw_hex(data));

			static constexpr uint8_t bandwidth_result[51] =
			{
				0x0F, 0xC1, 0x1C, 0x37, 0xB8, 0xEF, 0x7C, 0xD6, 0x00, 0x00, 0x04,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
			};

			byte_buffer buffer;
			buffer.write(sizeof(bandwidth_result), bandwidth_result);

			const auto reply = server->create_message(5);
			reply->send(&buffer, true);
		}
	};
}
